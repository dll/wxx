# 前言
高校是培养人才的重要基地。加强和改进学生工作是实现立德树人根本任务的重要途径。完善制度建设，规范学生教育管理服务，是学生工作基础工程。

近年来我校落实立德树人根本任务，坚持以学生为中心，依据教育部相关法规，修订完善全套学生管理制度，汇编形成本手册。全书分为上中下三篇：上篇校情介绍、中篇国家法规与学校章程、下篇校内管理规章，覆盖学籍学业、日常管理、奖惩、资助全维度。

无规矩不成方圆。本手册是约束学生行为、建设优良学风班风和校园文化的制度保障，也是全体师生教育管理、自我约束的依据。全体同学须认真学习、自觉遵守，践行“修德求是、博学笃行”校训，将个人理想融入国家发展，勤学奋进，在时代征程实现青春价值。


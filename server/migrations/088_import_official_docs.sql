# 下篇 学校规章制度
## （一）学籍、学业管理系列
### 1.《普通高等学校学生管理规定》滁州学院实施办法（校政学工〔2017〕46号）
完全依据教育部41号令细化校内操作，明确本校入学、注册、考勤、考核、转专业、休学、退学、奖惩、申诉全流程实施细则；处分期限：警告6个月、严重警告8个月、记过10个月、留校察看12个月；处分期满按申请解除；毕业未解除处分按结业处理。

### 2. 滁州学院本科生学年学分制学籍管理办法（校政教〔2017〕39号）
1. 弹性学制：四年制3-6年，不含休学；
2. 考勤管理：连续请假14天学院审批，超14天报教务处；旷课按实际课时计；
3. 绩点换算标准：90-100绩点4-5；80-89为3-3.9；70-79为2-2.9；60-69为1-1.9；不及格0；平均学分绩点=总学分绩/总学分；
4. 考核规则：不及格可重考1次，重考仍不及格必须重修；缺课超1/3取消考试资格；
5. 免修/自修/缓考流程；
6. 学业预警：一学期学分不足1/2触发红色预警，连续两红预警降级退学；
7. 毕业、结业、肄业区分；结业满足条件可换毕业证。

### 3. 学士学位授予工作实施细则（校政〔2025〕3号）
#### 授予基本条件
政治合格、修满学分、达到绩点、无严重学术不端；
#### 不授予学位情形
1. 平均学分绩点＜1.8；
2. 专业核心课4门及以上重修；
3. 在校受记过、留校察看处分；
4. 论文/成果抄袭代写；
#### 放宽特议条件（满足其一可豁免上述限制）
1. 考取全日制硕士；
2. 以本校为第一单位前三发明人获发明专利；
3. 省级二等/国三等以上学科竞赛第一负责人；
#### 撤销学位情形：入学造假、论文买卖剽窃等。

### 4. 普通本科学生转专业管理办法（校政教〔2025〕19号）
1. 申请时段：大一第一、二学期末；
2. 免试资格：当年高考录取排名专业前10%；
3. 禁止转专业人群：专升本、中外合作、定向、处分期、已转过一次、挂科、休学留级生；
4. 流程：线上申报→学院审核→接收学院考核→公示→校长办公会审批→变更学籍；
5. 退役复学、创业学生优先转专业。

### 5. 应征入伍大学生学籍与学业管理办法（校党字〔2023〕16号）
1. 新生入伍：保留入学资格至退役2年；在校生保留学籍至退役2年；
2. 学业优待：
   - 公体、军事理论、军训直接记良好学分；
   - 最多免5门公选课/任选课；
   - 服役总结可替代毕业实习；
   - 退役复学优先转专业；
   - 毕业当年入伍可提前答辩、线上考试；
3. 退役复学学分置换、课程替代政策。

### 6. 学业预警管理办法（校政教〔2023〕48号）
三级预警机制：
- **黄色预警**：单学期学分不足3/4，2门不及格，累计3门挂科；
- **橙色预警**：单学期学分不足2/3，3门不及格，累计4门挂科；
- **红色预警**：单学期学分不足1/2，4门不及格，累计5门挂科；连续两红预警降级退学；
橙色、红色预警必须告知家长，约谈面谈。毕业预警：累计6门挂科、绩点不足1.8、体测低于50分等。

### 7. 课程替代与学分认定（校政教〔2022〕41号）
适用转专业、转学、交流、参军、复学学生；思政、体育课不可替代；核心专业课不可替换；学分等效规则、每学期开学两周集中办理认定。

### 8. 学科竞赛管理与奖励办法（校政教〔2024〕13号）
竞赛分级：A类综合（互联网+、挑战杯）、国家级A类、省级A类、B类；明确各级赛事师生奖金封顶标准；竞赛成果可置换双创、第二课堂学分；造假追回奖金并处分。

### 9. 大创项目管理办法（校政教〔2023〕61号）
分创新训练、创业训练、创业实践三类；设国/省/校三级；结题标准含论文、专利、竞赛获奖、创业运营；经费专款专用，结题不合格收回资金。

### 10. 创新创业实践学分转换办法（校政教〔2019〕3号）
双创学分最低4学分，超出部分可兑换通识、专业选修课，最多兑换6学分，折算成绩85分。

### 11. 第二课堂成绩单实施办法（校政学工〔2023〕26号）
第二课堂为必修，总计12学分，5大模块：
1. 思想政治（≥3）；2. 专业创新（≥3）；3. 体育（≥2）；4. 文艺（≥2）；5. 志愿劳动（≥2）；
在校累计≥12学分方可毕业，退役学生体育、劳动模块直接达标；学分计入综测，系统统一记录存档。

### 12. 体质健康测试管理办法（校政教〔2024〕29号）
体测低于50分按结业；每年春秋两季测试；因病可免测；替考取消评优并违纪处分；成绩纳入综测与第二课堂。

### 13. 暑期社会实践管理办法（校政学工〔2023〕68号）
社会实践为必修，分三下乡、返家乡；团队实践不少于7天，计入第二课堂学分；每年评选优秀团队、调研报告。

## （二）综合管理系列
### 1. 学生文明行为准则
围绕爱国、勤学、守纪、宿舍文明、公共秩序、网络文明、爱护公物、外事礼仪十一条规范日常言行，禁止烟酒、打闹、作弊、私拉电线等。

### 2. 学生证管理办法
新生入学三月审核完成发放；每学期注册生效；仅限本人；遗失走学院证明+教务处补办；火车优惠卡仅限家校区间，不得涂改。

### 3. 学生公寓管理规定（校政〔2024〕23号）
1. 统一住宿，禁止私自租房；调换宿舍须审批；
2. 安全红线：严禁＞300W电器、电热毯、私拉电线、电动车室内充电、明火、宠物；
3. 访客登记，异性限公务时段进入，不留宿外人；
4. 内务垃圾分类，定时清扫；
5. 用电定额免费，超额自费；违规电器收缴并给予处分。

### 4. 城乡居民医保办法
全体在校生统一参保；校医院首诊，统筹基金报销80%；校外转诊合规费用报销60%；外伤、慢性病按政策补助，寒暑假门诊不予报销。

### 5. 图书馆规则
凭一卡通入馆，禁止占座、喧哗、饮食；学生可借10本，期限30天可续借；期刊、样本书不外借；偷窃、损毁图书给予校纪处分。

### 6. 学生社团管理细则（校党字〔2025〕46号）
社团注册需20名以上发起人、专职指导教师、业务主管单位；一年一次年审，分星级；社团不得盈利、开展宗教活动；活动必须提前审批，经费由学校统一管理，禁止私自收费。

### 7. 校园一卡通办法
一卡兼具身份、消费、门禁、图书功能；仅限本人，禁止转借；单笔消费超50元输密码；丢失及时挂失，补办工本费自理。

### 8. 宿舍网络管理
实名一人一号，禁止私设路由、服务器；P2P流量限制；严禁网络攻击、传播违法信息，违规暂停上网并处分。

### 9. 大一晚自习管理（19:30-21:10，周日至周四）
大一强制晚自习，考勤纳入学风考核；禁止玩手机、聊天、睡觉，因病事假提前向辅导员请假。

## （三）安全管理系列
### 1. 校园110：报警0550-3516110，24小时受理治安、急救、求助、火情。
### 2. 校园秩序管理
校外人员来访登记；禁止外卖、共享电动车入校；严禁私摆摊、湖塘游泳、高空抛物、23点后校园闲逛；讲座、集会必须审批。
### 3. 校园交通管理
校内限速30km/h，教学区禁鸣；电动车必须戴头盔，禁止带人；机动车依规注册，学生车辆不予备案；违规停车多次限制入校。
### 4. 监控调阅：掌上蔚园线上申请，学院+安保审批，仅可现场查看，禁止拷贝拍摄。
### 5. 门禁系统：人脸+车牌识别；外来访客线上预约登记；学生毕业自动注销人脸通行权限。

## （四）考核奖惩系列
### 1. 素质综合测评（德育15%+智育65%+体育10%+能力10%）
- 德育：自评20%、班级40%、辅导员40%，加减分项；违纪大幅扣分；
- 智育：纯课程加权平均分，补考不加分；
- 体育：体育课程、体测、长跑综合；
- 能力：依据第二课堂学分折算，作为奖学金、评优核心依据。

### 2. 奖学金与先进个人
奖学金三等：一等1200（3%）、二等800（7%）、三等500（12%）；对应三好学生标兵、三好学生、优秀学生；设立道德、创新创业、文体、参军报国单项奖；优秀毕业生按比例推荐。

### 3. 十佳班集体
全校每年评选10个最高荣誉班级，考核组织、思想、学风、安全、学生发展，奖励班级活动经费2000元。

### 4. 团内评优：优秀团员、团干、先进/五四红旗团支部，大一不参评。
### 5. 学生违纪处分办法（校政学工〔2025〕43号）
处分层级：警告、严重警告、记过、留校察看、开除；
重点违规处置：私用电、夜不归宿、酗酒、打架、作弊、网贷诈骗、翻墙离校、宗教活动、宿舍火灾隐患、网络造谣均有对应处分；
共同违纪区分主次，违法直接移交公安并加重校内处分。
### 6. 考试违纪、学生申诉配套细则：考试作弊成绩清零并处分；处分10日内提交书面申诉，15日内复核，不服可向省教育厅申诉。

## （五）资助管理系列
涵盖家庭经济困难认定、国家奖助学金、服兵役学费补偿、勤工助学、临时困难补助、学费减免/缓缴全流程；坚持精准资助，材料弄虚作假取消资格并通报。


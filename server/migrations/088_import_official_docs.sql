# 中篇 政策法规、学校章程
## 一、普通高等学校学生管理规定（教育部41号令，2017.9.1施行）
### 第一章 总则
1. 立法目的：规范高校管理，维护教学生活秩序，保障学生权益，培养合格建设者接班人。
2. 适用范围：全国普通高校、科研院所全日制硕本专科生。
3. 办学导向：立德树人，思政引领，依法治校，管理育人。
4. 学生基本义务与价值要求：拥护党的领导，坚定四个自信，爱国守法，勤学健体修身。
5. 管理原则：尊重权益，引导责任，支持学生“四自”（自我管理、服务、教育、监督）。

### 第二章 学生权利与义务
#### 权利（7条）
1. 参加教学活动、使用教学资源；
2. 社会实践、志愿服务、勤工助学、文体科创，就业指导；
3. 申请奖助贷学金；
4. 学业品德公正评价，达标取得毕业证、学位证；
5. 校内组织社团，参与学校管理，知情、表达、监督；
6. 对处分有异议可申诉；人身财产受侵害可维权；
7. 法律法规、章程规定其他权利。

#### 义务（6条）
1. 遵守宪法法律；
2. 遵守学校章程与制度；
3. 恪守学术诚信，完成学业；
4. 按时缴费，履行贷款/助学金约定；
5. 尊师守纪，养成良好品德行为；
6. 其他法定义务。

### 第三章 学籍管理
#### 第一节 入学注册
1. 新生持通知书按时报到，逾期无正当理由视为放弃入学资格；
2. 报到初审材料，造假取消入学资格；
3. 新生可申请保留入学资格；
4. 入学3个月全面复查，弄虚作假取消学籍；患病可保留入学资格；
5. 每学期按时注册，欠费不予注册；贫困生可贷款暂缓注册。

#### 第二节 考核与成绩
1. 所有教学环节必须考核，成绩记入档案；分考试、考查；
2. 思想品德：自评+民主评议；体育结合考勤、锻炼、体质综合打分；
3. 学分制管理，升级/留级标准校内制定；
4. 允许辅修、跨校选课、线上学分认定；
5. 创新创业、社会实践、论文专利可折算学分；
6. 成绩真实存档，补考/重修标注；作弊成绩无效，视情节处分；
7. 按时上课，无故旷课予以处分；
8. 建立学业诚信档案，学术失信限制学位荣誉。

#### 第三节 转专业、转学
1. 学生可申请转专业；定向、专项招生等有约定者不可转；退役复学、创业学生优先；
2. 转学限制：入学未满一学期、毕业前一年、高考分数低于目标校、专升本、定向生等不得转学；
3. 转学流程：本人申请，两校同意，跨省需省级教育部门协调备案。

#### 第四节 休学复学
1. 弹性学制，设定最长修业年限；
2. 学生可申请休学；创业学生简化流程、延长年限；
3. 参军学生保留学籍至退役2年；联合培养保留学籍；
4. 休学保留学籍，不享受在校待遇；期满按时复学。

#### 第五节 退学
退学情形：学业不达标、超期未复学、连续两周不上课、逾期未注册、伤病无法就读、本人申请退学；退学档案、户籍退回原籍。

#### 第六节 毕业/结业/肄业
1. 修满学分、考核合格准予毕业，颁发双证；
2. 修完课程但学分不足发结业，结业后可补考换证；
3. 退学发放肄业证或写实证明。

#### 第七节 证书管理
学历学位证按录取信息填写；信息变更需法定证明；证书电子注册；证书造假、学术不端可撤销注销；遗失可开等效证明书。

### 第四章 校园秩序与课外活动
1. 师生共建安全文明校园；
2. 健全学生代表大会制度，社团须审批登记；
3. 活动不得干扰教学生活秩序；勤工助学遵守法规；
4. 集会游行示威需法定审批；
5. 规范网络行为，禁止造谣、入侵网络；
6. 统一住宿管理，禁止私自外出租房。

### 第五章 奖励与处分
1. 德智体美突出学生予以表彰、奖学金；
2. 处分等级：警告、严重警告、记过、留校察看、开除学籍；
3. 开除学籍适用8类情形（违宪、犯罪、严重作弊、论文买卖剽窃、严重扰乱秩序等）；
4. 处分流程：告知事实、听取申辩、文书送达；重大处分校长办公会审议；
5. 除开除外处分设6-12个月期限，到期可解除；材料记入档案。

### 第六章 学生申诉
1. 设立学生申诉处理委员会；
2. 收到处分决定书10日内提交书面申诉；委员会15日内复查，复杂延长15日；
3. 不服复查15日内向省教育厅申诉；
4. 超期未申诉视为放弃，可向教育厅投诉学校侵权。

### 第七章 附则
本规定2017.9.1实施，原21号令废止。


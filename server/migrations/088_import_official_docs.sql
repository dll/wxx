## 三、学生伤害事故处理办法（教育部12号令）
### 总则
适用校内教学、活动及学校管理场所人身伤害案件；处理遵循合法客观。
### 责任划分
1. **学校担责**：设施不达标、安保疏漏、食品不合格、未安全教育、教师体罚、未及时救治等12类情形；
2. **学生/监护人担责**：违规冒险、隐瞒特异体质、不听劝阻等；
3. **学校无责**：地震洪水、校外突发侵害、学生自伤、体育对抗意外、上下学途中等；
4. 校外第三方致害由第三方担责。
### 处置流程
事发及时救助、上报；可协商、教育行政调解或诉讼；赔偿范围法定，学校垫付后可向责任人追偿；鼓励学生购买意外险。

## 四、国家教育考试违规处理办法（33号令）
### 一、违纪（取消单科成绩）
携带违禁物品、提前答题、交头接耳、擅自离场、带出试卷等。
### 二、作弊（所有科目成绩作废，可停考1-3年）
携带资料/电子设备、抄袭、替考、传答案、伪造证件、雷同卷等；团伙、通讯作弊等加重处罚。
### 三、扰乱考场秩序：所有成绩作废，移交公安
### 处理程序
两名工作人员取证，书面告知，15日内可复核，记入诚信档案；在校生作弊通报学校给予处分。

## 五、滁州学院章程
### 第一章 总则
1. 校名：滁州学院（Chuzhou University）；地址滁州琅琊西路2号；省属公办非营利高校；
2. 办学领导体制：党委领导下校长负责制；
3. 办学定位：地方性、应用型、开放式、信息化；目标省内一流、国内知名应用型大学。

### 第二章 举办者与权责
省政府举办、省教育厅主管；政府保障经费、考核办学；学校拥有招生、专业设置、人事、资产、教学等办学自主权。

### 第三章 办学职能
核心职能：人才培养、科研、社会服务、文化传承、国际交流；以本科为主，发展研究生教育，工学管理为主多学科协调；落实立德树人，产教融合，双创育人。

### 第四章 管理架构
1. **党委**：全面领导，管党治党，把握办学方向，决定重大事项、干部任免、思政、统战等；
2. **校长**：法定代表人，主持行政，分管教学科研人事财务招生就业安全；校长办公会为行政议事机构；
3. **纪委监察**：党内监督，执纪问责；
4. **学术委员会**：校内最高学术机构，审议学科、学位、师德、学术争议；
5. **学位评定委员会**：负责学位授予、撤销；
6. 教代会、学代会、工会、团委、各二级学院（校院两级管理）。

### 第五章 教职工
教师办学主体；享有教学科研、薪酬评聘、申诉等权利；履行师德育人、维护校誉义务；师德为聘用晋升首要标准。

### 第六章 学生
学生权利：教学资源、奖助、社团、申诉、民主管理；义务：守法守纪、完成学业、缴费、爱护公物、维护学校声誉；学校建立奖助、心理、就业、申诉机制。

### 第七章 经费资产
财政补助、事业收入等多渠道经费；统一财务、国有资产管理；勤俭办学，后勤保障。

### 第八章 学校与社会
信息公开，设立理事会、教育发展基金会；联络校友，服务地方产业。


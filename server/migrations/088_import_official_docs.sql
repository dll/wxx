# 上篇 学校情况介绍
## 一、学校简介
滁州学院前身1950年皖北滁州师范学校，历经滁县师范、安师大滁县教学点/分校，1980年升格滁州师专，2004年教育部批准设立滁州学院；2014年列为安徽省地方应用型高水平大学建设校，2024年获批硕士学位授予单位、安徽省应用特色建设高校。

### 荣誉称号

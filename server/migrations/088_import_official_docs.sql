# 滁州学院本科生“第二课堂成绩单”制度实施办法
## 第一章 总则
### 第一条 制定依据
为全面贯彻落实新时代党的教育方针，落实立德树人根本任务，深入推进学校深化新时代教育评价改革，根据《深化新时代教育评价改革总体方案》《关于在高校实施共青团“第二课堂成绩单”制度的意见》等文件精神，结合我校实际，制定本办法。

### 第二条 总体思路
以习近平新时代中国特色社会主义思想为指导，遵循高等教育与人才培养规律，按照**分层级、课程化、高质量**要求，构建覆盖德智体美劳五大维度的第二课堂育人机制，实现价值塑造、知识传授、能力培养有机融合，构建全员、全程、全方位育人格局。

### 第三条 目标任务
完善第二课堂工作体系，打造高品质第二课堂课程，建立五育并举综合素质评价机制；实现学生文化学习与品德修养、理论学习与社会实践、全面发展与个性发展三者统一，全面提升学生综合素养。

## 第二章 工作机构（校-院-班三级管理）
### 第四条 三级推进机制
制度实行学校、二级学院、班级三级统筹实施。

### 第五条 校级工作委员会
1. 组成：分管教学、分管学生工作校领导任主任；党委组织部、宣传部、教务处（创新创业学院）、学生处、信息化处、团委、体委办、马克思主义学院负责人为委员。
2. 职责：制定实施办法、统筹全校第二课堂建设管理。
3. 办公室：设在校团委，主任由团委书记兼任；负责课程规划、系统运维、日常监管、指导学院开展工作。

### 第六条 二级学院领导小组
1. 组成：学院党政负责人任组长，分管教学、学生工作副院长任副组长；院团委书记、学工办、系室主任为成员。
2. 职责：本院第二课堂课程规划、质量评价。
3. 办公室：院团委书记任主任，负责学分认证、日常监管、班级指导。

### 第七条 班级工作小组
辅导员任组长，团支书任副组长，全体班委、团支委组成；负责本班第二课堂落地执行。

## 第三章 学分设置
### 第八条 总学分要求
第二课堂纳入本科人才培养方案，**毕业最低总学分12学分**，分为五大模块，全部模块达标方可毕业：
1. 思想政治与品德：3学分
2. 专业技能与创新创业：3学分
3. 体育健身运动：2学分
4. 文化艺术修养：2学分
5. 志愿服务与劳动实践：2学分

### 第九条 思想政治与品德（3学分）
培养目标：树立理想信念，践行社会主义核心价值观，厚植爱国情怀、强化品德修养。
活动形式：主题党团日、团校青马培训、主题班会、三下乡社会实践、心理健康、廉洁教育、评优表彰、社会工作经历等。
**硬性要求：三下乡社会实践必修1学分**

### 第十条 专业技能与创新创业（3学分）
培养目标：理论结合实践，提升专业实操、创新能力。
活动形式：学科竞赛、双创项目、学术讲座、科研论文、专利、职业技能证书、创业实践。
**硬性要求：学术报告必修1学分**

### 第十一条 体育健身运动（2学分）
培养目标：强身健体、锤炼意志。
活动形式：各类体育赛事、校运动会、体质健康测试、日常文体锻炼。

### 第十二条 文化艺术修养（2学分）
培养目标提升人文审美、艺术创造力。
活动形式文艺汇演、书画展览、文艺比赛、美育讲座等。

### 第十三条 志愿服务与劳动实践（2学分）
培养劳动观念、社会服务意识。
活动形式：各类志愿活动、公益劳动、日常劳动、专业实践劳动。

### 第十四条 学分认证依据
第二课堂学分统一参照附件《滁州本科生第二课堂学分认证标准》执行。

### 第十五条 本科在校修读进度要求
学分建议前三年修满；
大一、大二每学年至少4学分，分模块最低标准：
- 思政、双创模块各≥1学分
- 体育、文艺、志愿劳动模块各≥0.7学分
三年级累计满12学分且全部模块达标视为学年合格。

### 第十六条 特殊学生学分标准
1. 专升本学生：在校仅需修满4学分，无模块必修限制，第一学年完成。
2. 学籍异动、中外合作办学：按实际在校学年折算学分要求。

### 第十七条 综测挂钩
第二课堂成绩单计入学生素质综合测评**能力发展测评**板块，按综测办法核算分数。

### 第十八条 免修认定情形
满足以下条件可申请对应模块免修、综测直接认定达标：
1. 身体、心理特殊困难：本人/辅导员书面申请，学院领导小组初审，学校委员会审定可免对应模块；
2. 退役复学学生：体育健身、志愿服务劳动两大模块直接认定达标。

## 第四章 组织实施
### 第十九条 校院两级职责
统筹课程规划、活动组织、学分审核、评价激励，建立学生主动参与、教师指导、规范管理的运行机制；第一课堂教学实践不计入第二课堂课程。

### 第二十条 课程分层分级规划
1. **分层（校、院两级）**
    - 校级课程：面向全体本科生，侧重综合素养拓展；
    - 院级课程：面向本院学生，强化专业能力；
    - 社团活动参照院级标准打造特色品牌课程。
2. **分级（分年级设计）**
    - 大一：思政、文体、入学导航类；
    - 大二、大三：专业实践、双创、社会服务；
    - 大四：原则不统一开设课程，学生自主补修未达标学分。

### 第二十一条 课程实施流程
1. **课程申请**：每年年底统一申报；上级临时活动至少提前5个工作日提交申请。
2. **课程审批**：学院/职能部门初审→校第二课堂委员会审定。
3. **课程公告**：审核通过统一公示，开课单位提交项目计划表备案。
4. **组织开展**：主办单位落实活动、宣传、材料归档、学分认定，落实安全管理。
5. **质量监控**：校、院办公室常态化督查；存在弄虚作假、管理混乱的课程责令整改、取消开课资格，追责相关人员。

### 第二十二条 学分预警与补修
大三期末学生登录系统核对成绩单，未达标须在大四第一学期完成补修；各学院定期预警未达标学生。

### 第二十三条 成绩等级（五级制）
总学分≥18：优秀
16≤学分＜18：良好
14≤学分＜16：中等
12≤学分＜14：合格
总分＜12 / 任一模块不达标：不合格

## 第五章 工作保障
### 第二十四条 场地设施
各单位提供活动场地、物资保障，鼓励学生参与。
### 第二十五条 信息化支撑
依托第二课堂管理系统实现课程发布、报名、活动记录、线上学分认证全流程线上办理。
### 第二十六条 指导教师激励
选配教师、团干部担任课程指导老师；指导工作量作为职称评审、评优、绩效分配重要参考。
### 第二十七条 课时冲突要求
第二课堂原则不与第一课堂教学时间冲突。
### 第二十八条 经费保障
第二课堂专项经费纳入学校年度预算，由主管部门落实。

## 第六章 附则
### 第二十九条 档案管理
第二课堂成绩单纳入本科生学业档案，学院统一打印归档。
### 第三十条 施行与废止
1. 本办法自**2026年9月1日**正式实施；
2. 同步废止两份旧文件：
    - 《滁州学院学生素质拓展与创新创业实践学分实施细则(修订)》校政学工〔2019〕50号
    - 《滁州学院本科生“第二课堂成绩单”制度实施办法 (试行)》校政学工〔2023〕26号
3. 未尽事宜由学校第二课堂工作委员会办公室解释。


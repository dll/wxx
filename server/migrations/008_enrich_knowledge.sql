6. 检查错别字、格式统一、PDF格式发送

Q3：面试有哪些常见问题和技巧？
A：
常见问题：
- "请做一下自我介绍"（控制在1-2分钟，突出与岗位匹配的经历）
- "你为什么选择我们公司/岗位？"（展示对公司和行业的了解）
- "你的优缺点？"（缺点说真实的但正在改进的）
- "你的职业规划？"（3-5年内成为该领域的专业人才）
- "你还有什么问题想问我们？"（问岗位发展、团队氛围等，不要问薪资）

面试技巧：
- 提前了解公司/岗位信息
- 准备2-3个有深度的提问
- 着装得体，提前10分钟到达
- 面试后24小时内发送感谢邮件

Q4：三方协议是什么？签了还能反悔吗？

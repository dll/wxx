1. 与原单位协商解约，取得解约函
2. 支付违约金（一般为一个约定金额，如3000-5000元）
3. 向学校申请换发新的三方协议
注意：每人只有一份三方协议，毁约后换发手续较繁琐，建议慎重签约。


Q2：简历怎么写才出彩？
A：
1. 一页为佳：HR平均每份简历只看10-20秒，简洁清晰最重要
2. 结构：个人信息 → 求职意向 → 教育背景 → 实习/项目经历 → 技能证书 → 获奖荣誉

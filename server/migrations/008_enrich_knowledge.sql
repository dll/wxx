Q2：社会实践学分怎么获得？
A：
社会实践为必修环节，计2学分。获取途径包括：
1. 暑期社会实践（不少于14天）：组队或独立完成，提交实践报告
2. 志愿服务：累计服务时长≥40小时（由校青协或学院青协认定）
3. 社区报到：参与社区服务活动≥2次
4. 企业参观/职业体验：至少参加1次学院组织的企业参访

Q3：社会实践报告怎么写？
A：
报告结构（不少于2000字）：
1. 封面（标题、姓名、学号、学院、实践时间）
2. 摘要（200字，概括实践内容和成果）
3. 正文：
   - 实践背景与目的
   - 实践过程（按时间顺序描述做了什么）
   - 实践成果（数据、照片、访谈记录等）
   - 问题与反思（发现的问题、自己的思考）
   - 建议与展望
4. 附录：实践照片（至少5张）、单位证明或鉴定表

Q4：志愿服务学分怎么认定？
A：
1. 志愿者在"志愿中国"或学院青协系统注册
2. 每次参加志愿活动后由组织方录入服务时长
3. 年度累计满20小时认定为合格，40小时优秀
4. 毕业前总时长不足40小时，需在毕业学期补足
5. 志愿服务类型包括：支教、敬老、环保、赛会服务、迎新志愿者等

Q5：哪些活动可以算社会实践？
A：
以下均可认定，但不重复计算：
- 暑期"三下乡"社会实践活动（团队或个人）
- 返家乡社会实践（寒暑假回原籍社区服务）
- 企业实习（与专业相关，不少于4周）
- 勤工助学岗位（校内，1学期以上）
- 红色教育基地参观学习
- 社会调查与研究（含问卷发放、数据分析）
- 创新创业实践（入驻创业孵化基地）
- 参与扶贫、支教等公益项目

